#!/bin/sh
# Publish the issue drafts in docs/issues/ (N01..N20) to GitHub, from YOUR account, with the gh CLI.
# Publica os rascunhos de docs/issues/ (N01..N20) no GitHub, da SUA conta, com o gh.
#
# Safe by default / seguro por padrão:
#   - without --publish it only PRINTS what it would do (dry run) / sem --publish só MOSTRA o que faria
#   - an issue whose title already exists (open or closed) is skipped, so running twice is harmless
#     / issue cujo título já existe (aberta ou fechada) é pulada; rodar duas vezes não duplica
#   - a draft that mentions an AI tool/assistant name is refused / rascunho que cita nome de ferramenta
#     de IA é recusado (project rule: no such mention in issues)
#   - labels are only applied with --with-labels (they must already exist in the repo)
#     / rótulos só com --with-labels (precisam já existir no repositório)
#
# Usage / Uso:
#   scripts/publish-issues.sh                         dry run, all drafts
#   scripts/publish-issues.sh --only N05,N06          dry run, just these
#   scripts/publish-issues.sh --publish --only N05    really create N05
#   options: --dir DIR (default docs/issues)  --repo OWNER/REPO (default: the gh default repo)
set -u
DIR=docs/issues; REPO=""; PUBLISH=0; LABELS=0; ONLY=""
while [ $# -gt 0 ]; do
  case "$1" in
    --publish) PUBLISH=1 ;;
    --with-labels) LABELS=1 ;;
    --only) shift; ONLY="${1:-}" ;;
    --dir) shift; DIR="${1:-}" ;;
    --repo) shift; REPO="${1:-}" ;;
    -h|--help) sed -n '2,19p' "$0"; exit 0 ;;
    *) echo "opção desconhecida / unknown option: $1" >&2; exit 2 ;;
  esac
  shift
done
[ -d "$DIR" ] || { echo "ERRO: pasta não encontrada / folder not found: $DIR" >&2; exit 2; }
command -v gh >/dev/null 2>&1 || { echo "ERRO: gh não encontrado / gh not found" >&2; exit 2; }
RARG=""; [ -n "$REPO" ] && RARG="--repo $REPO"

# Titles that already exist, one per line (also closed ones) / títulos que já existem (inclusive fechadas)
# shellcheck disable=SC2086
EXISTING=$(gh issue list $RARG --state all --limit 1000 --json title --jq '.[].title') || {
  echo "ERRO: não consegui listar as issues (gh logado?) / could not list issues (is gh logged in?)" >&2; exit 2; }

tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
created=0; skipped=0; refused=0; failed=0
for f in "$DIR"/N[0-9][0-9]-*.md; do
  [ -f "$f" ] || continue
  id=$(basename "$f" | cut -c1-3)
  if [ -n "$ONLY" ]; then case ",$ONLY," in *",$id,"*) ;; *) continue ;; esac; fi
  title=$(head -n 1 "$f" | sed 's/^# *//')
  [ -n "$title" ] || { echo "$id: ERRO título vazio / empty title"; failed=$((failed + 1)); continue; }
  if grep -qiE 'claude|anthropic|generated by|chatgpt|openai|copilot' "$f"; then
    echo "$id: RECUSADA — cita ferramenta/assistente de IA / REFUSED — mentions an AI tool or assistant"
    refused=$((refused + 1)); continue
  fi
  if printf '%s\n' "$EXISTING" | grep -qxF "$title"; then
    echo "$id: já existe, pulada / already exists, skipped — $title"; skipped=$((skipped + 1)); continue
  fi
  tail -n +2 "$f" > "$tmp/body.md"
  lab=""
  if [ "$LABELS" = 1 ]; then
    lab=$(grep -m1 '^\*\*Labels sugeridos:\*\*' "$f" | grep -o '`[^`]*`' | tr -d '`' | paste -sd, -)
  fi
  if [ "$PUBLISH" != 1 ]; then
    echo "$id: [dry-run] criaria / would create — $title${lab:+  (labels: $lab)}"; created=$((created + 1)); continue
  fi
  # shellcheck disable=SC2086
  if gh issue create $RARG --title "$title" --body-file "$tmp/body.md" ${lab:+--label "$lab"} >/dev/null; then
    echo "$id: criada / created — $title"; created=$((created + 1))
  else
    echo "$id: FALHOU ao criar / FAILED to create — $title"; failed=$((failed + 1))
  fi
done
mode="dry-run"; [ "$PUBLISH" = 1 ] && mode="publicado / published"
echo "resumo / summary ($mode): $created a criar-ou-criadas, $skipped puladas, $refused recusadas, $failed falhas"
[ "$failed" = 0 ] && [ "$refused" = 0 ]
